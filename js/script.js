/* ==========================
   VARIABLES DE LA GALERÍA
========================== */

let propiedadActual = "";
let indice = 0;


/* ==========================
   VER / OCULTAR PROPIEDADES
========================== */

function mostrarTodasLasPropiedades(event) {
    event.preventDefault();

    const seccion = document.getElementById("propiedades");
    const boton = document.getElementById("btnVerPropiedades");

    seccion.classList.toggle("mostrar-todas");

    const mostrandoTodas =
        seccion.classList.contains("mostrar-todas");

    boton.textContent = mostrandoTodas
        ? "Ocultar propiedades"
        : "Ver Propiedades";

    if (mostrandoTodas) {
        seccion.scrollIntoView({
            behavior: "smooth",
            block: "start"
        });
    } else {
        document.querySelector(".hero").scrollIntoView({
            behavior: "smooth",
            block: "start"
        });
    }
}


/* ==========================
   ABRIR GALERÍA
========================== */

function abrirGaleria(nombre) {
    if (!propiedades[nombre]) {
        console.error("No se encontró la propiedad:", nombre);
        return;
    }

    propiedadActual = nombre;
    indice = 0;

    document.getElementById("modal").style.display = "block";
    document.body.style.overflow = "hidden";

    document.getElementById("tituloPropiedad").textContent =
        propiedades[nombre].titulo;

    document.getElementById("infoPropiedad").innerHTML =
        propiedades[nombre].descripcion;

    const mensaje =
        `Hola Grupo Raíz.

Me interesa la propiedad ${propiedades[nombre].titulo}.

¿Sigue disponible?

Me gustaría recibir más información.

Muchas gracias.`;

    document.getElementById("btnWhatsapp").href =
        `https://wa.me/50433528723?text=${encodeURIComponent(mensaje)}`;

    document.getElementById("btnCorreo").href =
        `mailto:gruporaizsderldecv@gmail.com?subject=${encodeURIComponent(
            "Consulta sobre " + propiedades[nombre].titulo
        )}&body=${encodeURIComponent(mensaje)}`;

    actualizarImagen();
}


/* ==========================
   ACTUALIZAR IMAGEN
========================== */

function actualizarImagen() {
    const imagen = document.getElementById("imagenGaleria");
    const contador = document.getElementById("contador");
    const lista = propiedades[propiedadActual].imagenes;

    imagen.src = lista[indice];

    contador.textContent =
        `Imagen ${indice + 1} de ${lista.length}`;

    imagen.onerror = function () {
        console.error("No se pudo cargar la imagen:", imagen.src);
    };
}


/* ==========================
   IMAGEN SIGUIENTE
========================== */

function siguiente() {
    if (!propiedadActual) return;

    indice++;

    if (indice >= propiedades[propiedadActual].imagenes.length) {
        indice = 0;
    }

    actualizarImagen();
}


/* ==========================
   IMAGEN ANTERIOR
========================== */

function anterior() {
    if (!propiedadActual) return;

    indice--;

    if (indice < 0) {
        indice = propiedades[propiedadActual].imagenes.length - 1;
    }

    actualizarImagen();
}


/* ==========================
   CERRAR GALERÍA
========================== */

function cerrarGaleria() {
    document.getElementById("modal").style.display = "none";
    document.body.style.overflow = "";

    propiedadActual = "";
    indice = 0;
}


/* ==========================
   TECLADO Y CIERRE DEL MODAL
========================== */

document.addEventListener("keydown", function (e) {
    const modal = document.getElementById("modal");

    if (modal.style.display !== "block") {
        return;
    }

    if (e.key === "ArrowRight") {
        siguiente();
    }

    if (e.key === "ArrowLeft") {
        anterior();
    }

    if (e.key === "Escape") {
        cerrarGaleria();
    }
});


/* Cerrar al pulsar fuera del contenido de la galería */
document.getElementById("modal").addEventListener("click", function (e) {
    if (e.target === this) {
        cerrarGaleria();
    }
});
